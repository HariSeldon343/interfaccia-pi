  function risolviTema(scelta, schemaSistema) {
    if (scelta === "notte") return "notte";
    if (scelta === "automatico" && schemaSistema === "dark") return "notte";
    return "caldo";
  }

  function applicaTema(documento, tema, schemaSistema) {
    const risolto = risolviTema(tema, schemaSistema);
    const radice = documento?.documentElement;
    if (!radice) return risolto;
    radice.setAttribute("data-tema", risolto);
    if (radice.style) radice.style.colorScheme = risolto === "notte" ? "dark" : "light";
    return risolto;
  }

  function luminanza(colore) {
    if (typeof colore !== "string" || !/^#?[a-f\d]{6}$/iu.test(colore)) {
      throw new TypeError("Il colore deve essere un esadecimale a sei cifre.");
    }
    const canali = colore.replace(/^#/u, "").match(/.{2}/gu).map((canale) => {
      const valore = parseInt(canale, 16) / 255;
      return valore <= 0.04045 ? valore / 12.92 : ((valore + 0.055) / 1.055) ** 2.4;
    });
    return 0.2126 * canali[0] + 0.7152 * canali[1] + 0.0722 * canali[2];
  }

  function contrasto(coloreA, coloreB) {
    const a = luminanza(coloreA);
    const b = luminanza(coloreB);
    return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
  }

  return { PALETTE, risolviTema, applicaTema, contrasto };
